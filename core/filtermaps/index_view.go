package filtermaps

type IndexView struct {
	f       *FilterMaps
	maps    common.Range[uint32]
	blocks  common.Range[uint64] // fully rendered blocks
	overlay []*mapOverlay
}

type mapId struct {
	mapIndex        uint32
	lastBlockNumber uint64
	lastBlockId     common.Hash
}

type mapOverlay struct {
	mapId
	fm                filterMap
	lastBlockComplete bool
	nextLvPtr         uint64
	blockLvPtrs       []uint64
	parent            mapId
}

// GetParams returns the filtermaps parameters.
// GetParams implements MatcherBackend.
func (dv *dbIndexView) GetParams() *Params {
	return &dv.f.Params
}

